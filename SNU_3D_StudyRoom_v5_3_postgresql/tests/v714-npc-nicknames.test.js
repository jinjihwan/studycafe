test('V7.14 NPC nicknames match the approved 144 nicknames in exact order',()=>{
 const actual=VIRTUAL_CAMPUSES.flatMap(campus=>VIRTUAL_NAMES[campus]);
 assert.equal(actual.length,144);
 assert.equal(new Set(actual).size,144);
 assert.deepEqual(actual,approvedNames);
 for(let c=0;c<VIRTUAL_CAMPUSES.length;c++){
  const campus=VIRTUAL_CAMPUSES[c];
  assert.equal(VIRTUAL_NAMES[campus].length,VIRTUAL_POPULATION);
  for(let id=0;id<VIRTUAL_POPULATION;id++){
   assert.equal(virtualProfile(campus,id).nick,approvedNames[c*VIRTUAL_POPULATION+id]);
  }
 }
});
