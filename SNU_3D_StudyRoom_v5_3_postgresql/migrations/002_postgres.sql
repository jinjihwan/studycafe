-- v5.3 PostgreSQL account and friend migration. Additive, repeatable, no data deletion.
-- UUID-like internal IDs are 32-character hex values (retained from v4/v5).
BEGIN;
CREATE TABLE IF NOT EXISTS accounts (
 user_id CHAR(32) PRIMARY KEY REFERENCES guests(id),
 firebase_uid TEXT UNIQUE NOT NULL,
 friend_code VARCHAR(13) UNIQUE NOT NULL,
 activity_public BOOLEAN NOT NULL DEFAULT TRUE,
 join_allowed BOOLEAN NOT NULL DEFAULT TRUE,
 friend_ranking_public BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS guest_consumed (
 guest_id CHAR(32) PRIMARY KEY REFERENCES guests(id),
 account_id CHAR(32) NOT NULL REFERENCES guests(id),
 merged_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS app_sessions (
 token_hash CHAR(64) PRIMARY KEY,
 user_id CHAR(32) NOT NULL REFERENCES guests(id),
 csrf_hash CHAR(64) NOT NULL,
 csrf_token TEXT NOT NULL,
 expires_at BIGINT NOT NULL,
 created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS app_session_user_idx ON app_sessions(user_id);
CREATE TABLE IF NOT EXISTS friend_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sender CHAR(32) NOT NULL REFERENCES guests(id),
 target CHAR(32) NOT NULL REFERENCES guests(id),
 state VARCHAR(10) NOT NULL DEFAULT 'pending' CHECK(state IN ('pending','accepted','rejected','cancelled')),
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS friend_requests_target_idx ON friend_requests(target,state);
CREATE INDEX IF NOT EXISTS friend_requests_sender_idx ON friend_requests(sender,state);
CREATE UNIQUE INDEX IF NOT EXISTS friend_requests_pending_pair_idx
 ON friend_requests ((LEAST(sender,target)),(GREATEST(sender,target))) WHERE state='pending';
CREATE TABLE IF NOT EXISTS friends (
 a CHAR(32) NOT NULL REFERENCES guests(id), b CHAR(32) NOT NULL REFERENCES guests(id),
 created_at BIGINT NOT NULL,
 PRIMARY KEY(a,b),CHECK(a<b)
);
CREATE TABLE IF NOT EXISTS blocks (
 blocker CHAR(32) NOT NULL REFERENCES guests(id),blocked CHAR(32) NOT NULL REFERENCES guests(id),
 created_at BIGINT NOT NULL,
 PRIMARY KEY(blocker,blocked),CHECK(blocker<>blocked)
);
CREATE TABLE IF NOT EXISTS room_policies (
 room_id VARCHAR(32) PRIMARY KEY,
 owner_id CHAR(32) NOT NULL REFERENCES guests(id),
 is_private BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS room_access (
 room_id VARCHAR(32) NOT NULL REFERENCES room_policies(room_id) ON DELETE CASCADE,
 user_id CHAR(32) NOT NULL REFERENCES guests(id),
 granted_at BIGINT NOT NULL,
 PRIMARY KEY(room_id,user_id)
);
COMMIT;
